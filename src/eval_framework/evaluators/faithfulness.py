"""Faithfulness evaluator - Does the answer stay true to source documents?"""

import re
import json
from typing import Optional

from ..types import (
    QAPair,
    SystemOutput,
    EvaluationMetric,
)
from ..utils.llm_client import LLMClient
from .base import BaseEvaluator


class FaithfulnessEvaluator(BaseEvaluator):
    """Evaluates whether the system's answer is faithful to the provided context.
    
    Faithfulness measures if the answer contains claims that are:
    - Supported by the provided context
    - Not contradictory to the context
    - Not hallucinated without source evidence
    
    Example:
        Context: "Paris is the capital of France"
        Question: "What is the capital of France?"
        Good answer: "Paris is the capital of France" (faithful, grounded)
        Bad answer: "Paris is the capital of France and has 50 million people"
        (unfaithful - population claim not in context)
    """
    
    @property
    def metric(self) -> EvaluationMetric:
        return EvaluationMetric.FAITHFULNESS
    
    @property
    def system_prompt(self) -> str:
        return """You are an expert evaluator assessing whether LLM outputs are faithful to their source documents.

Faithfulness means:
1. Claims are directly supported by the provided context
2. No contradictions with the context
3. No hallucinated details not supported by sources

You will be given:
- Context (source documents)
- Question asked
- Answer generated by an LLM

Your task: Evaluate how faithful the answer is to the context.

Score 1.0: Every claim is supported by context, no hallucinations
Score 0.8: Minor unsupported details (1-2 claims) but core is faithful
Score 0.5: Mixed - some supported claims, some hallucinated
Score 0.2: Mostly hallucinated with little grounding
Score 0.0: Completely hallucinated or contradicts context

Respond with a JSON object containing:
{
  "score": <float 0-1>,
  "unsupported_claims": [<list of hallucinated claims>],
  "contradictions": [<list of claims contradicting context>],
  "supported_claims": [<list of well-grounded claims>],
  "reasoning": "<brief explanation of the score>"
}"""
    
    def format_prompt(
        self,
        qa_pair: QAPair,
        system_output: SystemOutput,
    ) -> str:
        context_section = ""
        if qa_pair.context:
            context_section = f"""CONTEXT (Source Documents):
{qa_pair.context}

"""
        
        return f"""{context_section}QUESTION:
{qa_pair.question}

REFERENCE ANSWER:
{qa_pair.answer}

SYSTEM OUTPUT:
{system_output.answer}

Evaluate the faithfulness of the system output above."""
    
    async def parse_judge_response(self, response: str) -> tuple[float, str]:
        """Parse JSON response from judge."""
        try:
            # Try to extract JSON from response
            # Sometimes LLMs include extra text before/after JSON
            json_match = re.search(r'\{.*\}', response, re.DOTALL)
            if json_match:
                json_str = json_match.group()
                data = json.loads(json_str)
                score = float(data.get("score", 0.5))
                reasoning = data.get("reasoning", "No reasoning provided")
                return score, reasoning
            else:
                # Fallback: try to parse entire response as JSON
                data = json.loads(response)
                score = float(data.get("score", 0.5))
                reasoning = data.get("reasoning", "No reasoning provided")
                return score, reasoning
        except json.JSONDecodeError:
            # If JSON parsing fails, extract score using regex
            score_match = re.search(r'score["\s:]*(\d+\.?\d*)', response.lower())
            if score_match:
                score = float(score_match.group(1)) / 100 if float(score_match.group(1)) > 1 else float(score_match.group(1))
                return max(0, min(1, score)), response[:200]
            return 0.5, response[:200]
